"""Куда поставить метку, чтобы она не закрывала чертёж.

Метка должна попасть на свободное место рядом со своим объектом: если она
легла на подпись или на линию, модель читает не то, что должна. Искать место
перебором смещений нельзя — на листе 4 в вырезе подписи «1» метка «N8» садилась
на верхний край рамки знака и цифра внутри квадрата становилась нечитаемой,
хотя по коду стояла «рядом».

Поэтому место ищется по карте расстояний: сначала строится карта свободного
пространства вокруг объекта, потом по ней ставится метка на наименее
затронутом пятне. Отдельно учитывается точка привязки — метка должна остаться
рядом со своим объектом, а не улететь в свободный угол выреза.

Метод тот же, что и в исходной идее: двоичная маска линий, морфологическое
расширение на несколько пикселей, расстояние до ближайшей линии, штраф за
перекрытие. Здесь это сделано на numpy без OpenCV — зависимость от него ради
одной функции не нужна, а ``scipy`` в проекте уже есть.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import scipy.ndimage as ndi

# На сколько пикселей расширяется каждая линия, прежде чем считаться
# препятствием. Метка не должна подходить к чертежу вплотную: у края буквы
# остаётся серый от сглаживания, и подложка метки рядом с линией выглядит как
# разрыв в графике.
BUFFER_PX = 3
# Порог, ниже которого линия считается нарисованной. Лист чёрно-белый, но
# после сглаживания тонкая линия даёт серый, и при низком пороге в маску
# попадает весь фон.
INK_LEVEL = 200
# Во сколько раз перекрытие меткой чертежа дороже расстояния до привязки.
# Штраф такой величины, что метка встанет в свободное место даже в двадцати
# пунктах от объекта, но не ляжет на линию ни при каких условиях: иначе она
# закрывает именно то, ради чего вырез и делался.
OVERLAP_PENALTY = 10000.0
# На каком расстоянии от привязки метка ещё считается «своей». Метка должна
# остаться рядом со своей подписью, иначе модель не поймёт, к какой вопрос:
# на десяти листах при радиусе в 60 пикселей нашлось 455 чистых мест из 573,
# а остальные вырезы — плотная графика, где свободного пятна рядом нет.
SEARCH_PX = 150
# Шаг перебора привязок. Мелкий шаг даёт гладкий выбор, но перебор идёт по
# позициям метки, а не по пикселям всего выреза, и стоит копейки.
STEP_PX = 4


@dataclass(frozen=True)
class Placement:
    """Где стоит метка и почему."""

    x: int
    y: int
    overlap: int          # сколько пикселей чертежа под меткой
    distance: int         # насколько далеко от привязки, в пикселях


def free_map(gray: np.ndarray, buffer_px: int = BUFFER_PX,
             ink: int = INK_LEVEL) -> np.ndarray:
    """Карта расстояний от нарисованного до ближайшего пустого места.

    Возвращает расстояние в пикселях для каждой точки выреза: **чем больше
    значение, тем свободнее место**, и ноль стоит на самой линии.

    Здесь важна одна деталь, на которой карта легко переворачивается.
    ``distance_transform_edt`` считает расстояние до ближайшего **нуля**, а не
    до ближайшего единичного пикселя: нули у нас — это линии. Функция вызвана
    на инвертированной маске, иначе расстояние считается наоборот — на линии
    выходит единица, а в чистом поле ноль. С неверным знаком условие «метка
    накрывает чертёж» выполнялось всегда, поиск свободного места не находил
    ничего никогда, а метка вставала куда попало. На листе 4 это давало
    накрытие от 760 до 2322 пикселей на каждый вырез вместо нуля.

    Расширение на ``buffer_px`` делает расстояние «до безопасной зоны», а не
    «до линии»: метка не должна подходить к графике вплотную.
    """
    drawn = (gray < ink)
    if not drawn.any():
        return np.full(gray.shape, float(max(buffer_px, 1) * 8.0),
                       dtype=np.float32)
    grown = ndi.binary_dilation(drawn, _kernel(buffer_px))
    return ndi.distance_transform_edt(~grown).astype(np.float32)


def _kernel(size: int) -> np.ndarray:
    """Квадратная structuring element для расширения."""
    side = max(1, int(size))
    return np.ones((side, side), dtype=bool)


def forbid(free: np.ndarray, box, area, scale: float, pad: float = 1.0) -> None:
    """Объявить прямоугольник непригодным для метки.

    Расстояние внутри прямоугольника обнуляется, и такие позиции поиском больше
    не выбираются: у них перекрытие ненулевое, а штраф за перекрытие такой, что
    они проигрывают любой свободной позиции.

    Нужно для самой подписи, вокруг которой строится вырез. Подпись — цель
    вопроса, и накрыть её меткой нельзя ни при каких условиях: на листе 4
    подложка «N10» вставала прямо на «<8>», и модель видела обрывки цифр
    вместо текста. Соседние линии для метки считаются чертёжом, а сама надпись
    — нет, и карта расстояний об этом не знает.
    """
    x0 = int((box.x0 - pad - area.x0) * scale)
    y0 = int((box.y0 - pad - area.y0) * scale)
    x1 = int((box.x1 + pad - area.x0) * scale) + 1
    y1 = int((box.y1 + pad - area.y0) * scale) + 1
    x0, y0 = max(0, x0), max(0, y0)
    x1, y1 = min(free.shape[1], x1), min(free.shape[0], y1)
    if x1 > x0 and y1 > y0:
        free[y0:y1, x0:x1] = 0.0


def place(
    free: np.ndarray,
    anchor: tuple[int, int],
    size: tuple[int, int],
    search: int = SEARCH_PX,
    step: int = STEP_PX,
    penalty: float = OVERLAP_PENALTY,
) -> Placement:
    """Найти место для метки размера ``size`` рядом с ``anchor``.

    Перебираются позиции вокруг привязки; для каждой считается, сколько
    пикселей чертежа попало под метку, и выбирается наименьшая сумма штрафа и
    расстояния. Подложка метки одноцветна, поэтому линия под ней пропала бы
    бесследно, и метка не должна наезжать на графику ни при каких условиях.
    """
    width, height = size
    rows, cols = free.shape
    if width >= cols or height >= rows:
        # Метка не помещается в вырез нигде — искать нечего. Возвращается
        # левый верхний угол, и подпись обрежется по краю: лучше срезанная
        # метка, чем исключение посреди разметки листа.
        return Placement(0, 0, overlap=0, distance=0)

    # Привязка зажимается внутрь: координаты приходят из геометрии листа, и
    # подпись у самого края даёт якорь вне выреза.
    ax = min(max(int(anchor[0]), 0), cols - 1)
    ay = min(max(int(anchor[1]), 0), rows - 1)

    best = Placement(ax, ay, overlap=0, distance=0)
    best_score = float("inf")

    for dy in range(-search, search + 1, step):
        y = ay + dy
        if y < 0 or y + height >= rows:
            continue
        for dx in range(-search, search + 1, step):
            x = ax + dx
            if x < 0 or x + width >= cols:
                continue
            # Число пикселей чертежа под меткой: там, где расстояние до
            # линии меньше буфера, места нет.
            patch = free[y:y + height, x:x + width]
            overlap = int(np.count_nonzero(patch < 1.0))
            distance = float(np.hypot(dx, dy))
            score = distance + overlap * penalty
            if score < best_score:
                best_score = score
                best = Placement(x, y, overlap, int(distance))

    return best


def label_box(
    text: str,
    position: tuple[int, int],
    size: tuple[float, float],
    px_per_pt: float,
) -> tuple[float, float, float, float]:
    """Прямоугольник подложки метки в пунктах PDF.

    Считается по габаритам текста в пикселях, переведённым обратно в пункты:
    иначе подложка либо не покрывает буквы, либо накрывает лишнее.
    """
    x, y = position
    width, height = size
    return (x / px_per_pt, y / px_per_pt,
            (x + width) / px_per_pt, (y + height) / px_per_pt)
