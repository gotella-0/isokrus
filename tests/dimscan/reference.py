"""Эталон листов и проверка достижимости.

Главное здесь — ``PER_SHEET``: поразмерный список размеров, входящих в длину
трассы. Сумма ``EXPECTED`` считается из него, а не хранится отдельно.

Зачем отдельный модуль. Разбор листа и проверка разбора — разные вещи, и
проверять их надо по отдельности, иначе зелёный статус одного слоя прикроет
провал другого:

* **«все размеры найдены»** (``reachable``) — набирается ли эталонная сумма
  набором найденных чисел. Набирается — значит все нужные размеры найдены и
  лишних нет. Это проверка **поиска**;
* **«разница»** (``chain_total``) — что даёт иерархия «обобщённый /
  вложенный». Это **другой слой**, и в этом слое расхождение ожидаемо:
  рисунок нарисован не в масштабе (на листе 5 от 1.34 до 20.95 мм на пункт),
  а ряды размеров разных ветвей перекрываются по проекции. Родителя из
  геометрии размерной линии не восстановить — нужна топология трассы, а она
  ищется по картинке и координатам привязки в ``research/exp_04``.

Значения — длины трасс по листам ``02_Изометрии_10_листов.pdf``, снятые
вручную. Сумма вложенных участков **не обязана** равняться обобщённому:
на изометрии звенья под обобщённым размером нарисованы не все, поэтому
``arithmetic_ok`` в выгрузке — предупреждение, а не критерий.
"""

from __future__ import annotations

from typing import Sequence

# Поразмерный эталон: какие именно размеры входят в длину трассы, мм.
#
# Заполнен по всем десяти листам. Значения идут в том порядке, в котором
# сняты с чертежа; порядок ничего не значит, важен только набор, и повторы
# значений значимы: на листе 9 два размера по 123, на листе 10 два по 341.
#
# Почему список, а не сумма. По одной сумме отличить неверный набор от верного
# нельзя: на листе 3 и на листе 4 существует по два равнозначных набора, и
# проверка «сумма сошлась» пропускала бы половину ошибок. Так и вышло: эталон
# листа 3 стоял как 6079 вместо 6393, и по нему «не взяты 146 и 168»
# читалось как системная ошибка модели — в десяти прогонах подряд, — хотя эти
# два размера в трассу входят.
PER_SHEET: dict[int, tuple[int, ...]] = {
    1: (320, 200, 900, 2160, 600, 1383),
    2: (730, 1406, 174, 1900, 150, 10200, 5644, 1350, 293, 224),
    3: (210, 13, 178, 168, 146, 200, 228, 224, 198, 264, 1250, 950, 2364),
    4: (250, 214, 159, 214, 155, 504, 378, 159, 81, 81, 171, 159, 154,
        380, 159),
    5: (285, 651, 850, 450, 2400, 34, 3505),
    6: (285, 651, 850, 2950, 2400, 34, 3505),
    7: (60, 1950, 34, 650, 840, 522, 250),
    8: (23525, 1000, 24100),
    9: (195, 123, 244, 123, 175),
    10: (154, 244, 341, 220, 188, 134, 2450, 341, 244, 149, 220, 135,
         134, 200),
}

# Суммы берутся из ``PER_SHEET``, а не хранятся отдельно.
#
# Именно из-за того, что раньше они хранились отдельно, эталон листа 3 и разой��ся
# с поразмерным: правка набора без правки суммы прошла незамеченной. Считать
# одно из другого — единственный способ такие расхождения исключить.
EXPECTED: dict[int, float] = {
    page: float(sum(values)) for page, values in PER_SHEET.items()
}


def reachable(values: Sequence[float], target: float) -> list[float] | None:
    """Набор чисел, дающий в сумме ``target``, или ``None``.

    Перебором всех подмножеств: на листе 2 их 65 тысяч, на листе 8 — 4096,
    и для десятка листов это дешёво. Листов с двадцатью размерами не бывает,
    но если встретится — срабатывает жадный подбор: сперва самые крупные,
    остаток добираем мелкими. Жадный ответ может не найтись там, где набор
    есть, поэтому ``None`` означает «не доказано, что невозможно», и это
    видно по строке отчёта.

    Из наборов берётся самый **короткий**: эталон — это сумма обобщённых
    размеров, а обобщённых на листе мало, вложенных — много. Иначе в отчёт
    попадал бы набор из мелочи, и столбец «не вошли в эталон» показывал бы
    не вложенные размеры, а наоборот — сами обобщённые.
    """
    items = [float(v) for v in values]
    n = len(items)
    if n == 0 or target < 0:
        return None
    if n > 20:
        return _greedy(items, target)
    best_mask = 0
    best_count = n + 1
    for mask in range(1 << n):
        count = bin(mask).count("1")
        if count >= best_count:
            continue  # набор не короче лучшего — сумму считать незачем
        total = 0.0
        for i in range(n):
            if mask >> i & 1:
                total += items[i]
        if abs(total - target) < 0.5:
            best_mask = mask
            best_count = count
    if not best_count:
        return None
    return [items[i] for i in range(n) if best_mask >> i & 1]


def _greedy(items: Sequence[float], target: float) -> list[float] | None:
    """Жадный подбор: сперва большие, остаток добираем мелкими."""
    chosen: list[float] = []
    rest = target
    for value in sorted(items, reverse=True):
        if value <= rest + 0.5:
            chosen.append(value)
            rest -= value
    return chosen if abs(rest) < 0.5 else None


def _greedy(items: Sequence[float], target: float) -> list[float] | None:
    """Жадный подбор: сперва большие, остаток добираем мелкими."""
    chosen: list[float] = []
    rest = target
    for value in items:
        if value <= rest + 0.5:
            chosen.append(value)
            rest -= value
    return chosen if abs(rest) < 0.5 else None
