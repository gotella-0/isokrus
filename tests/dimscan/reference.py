def reachable(values: Sequence[float], target: float) -> list[float] | None:
    """Набор чисел, дающий в сумме ``target``, или ``None``.

    Перебором всех подмножеств: на листе 2 их 65 тысяч, на листе 8 — 4096,
    и для десятка листов это дешёво. Листов с двадцатью размерами не бывает,
    но если встретится — срабатывает жадный подбор: сперва самые крупные,
    остаток добираем мелкими. Жадный ответ может не найтись там, где набор
    есть, поэтому ``None`` означает «не доказано, что невозможно», и это
    видно по строке отчёта.

    Из наборов берётся самый **короткий**: эталон — это сумма обобщённых
    размеров, а обобщённых на листе мало, вложенных — много. Иначе в отчёт
    попадал бы набор из мелочи, и столбец «не вошли в эталон» показывал бы
    не вложенные размеры, а наоборот — сами обобщённые.
    """
    items = [float(v) for v in values]
    n = len(items)
    if n == 0 or target < 0:
        return None
    if n > 20:
        return _greedy(items, target)
    best_mask = 0
    best_count = n + 1
    for mask in range(1 << n):
        count = bin(mask).count("1")
        if count >= best_count:
            continue  # набор не короче лучшего — сумму считать незачем
        total = 0.0
        for i in range(n):
            if mask >> i & 1:
                total += items[i]
        if abs(total - target) < 0.5:
            best_mask = mask
            best_count = count
    if not best_count:
        return None
    return [items[i] for i in range(n) if best_mask >> i & 1]


def _greedy(items: Sequence[float], target: float) -> list[float] | None:
    """Жадный подбор: сперва большие, остаток добираем мелкими."""
    chosen: list[float] = []
    rest = target
    for value in sorted(items, reverse=True):
        if value <= rest + 0.5:
            chosen.append(value)
            rest -= value
    return chosen if abs(rest) < 0.5 else None


