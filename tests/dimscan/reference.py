"""Эталонные суммы листов и проверка достижимости.

Зачем отдельный модуль. Разбор листа и проверка разбора — разные вещи, и
проверять их надо по отдельности, иначе зелёный статус одного слоя прикроет
провал другого:

* **«все размеры найдены»** (``reachable``) — набирается ли эталонная сумма
  набором найденных чисел. Набирается — значит все нужные размеры найдены и
  лишних нет. Это проверка **поиска**;
* **«разница»** (``chain_total``) — что даёт иерархия «обобщённый /
  вложенный». Это **другой слой**, и в этом слое расхождение ожидаемо:
  рисунок нарисован не в масштабе (на листе 5 от 1.34 до 20.95 мм на пункт),
  а ряды размеров разных ветвей перекрываются по проекции. Родителя из
  геометрии размерной линии не восстановить — нужна топология трассы, а она
  ищется по картинке и координатам привязки в ``research/exp_04``.

Значения — длины трасс по листам ``02_Изометрии_10_листов.pdf``, снятые
вручную. Сумма вложенных участков **не обязана** равняться обобщённому:
на изометрии звенья под обобщённым размером нарисованы не все, поэтому
``arithmetic_ok`` в выгрузке — предупреждение, а не критерий.
"""

