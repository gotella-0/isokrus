"""Второй фронтенд разбора изометрии: всё берётся из растра.

Зачем он нужен рядом с ``tests/dimscan``. Там работают два источника правды
из PDF: векторные команды рисования (``page.get_drawings``) и текстовый слой
(``page.get_text``). Оба исчезают, если чертёж пришёл сканом: в PDF остаётся
одна картинка, и ``get_drawings`` возвращает пустой список. Причём тихо —
без исключения, просто ноль результата.

Здесь те же размерные линии и те же числа добываются из картинки: наконечники
стрелок ищутся по контурам, числа читаются OCR. На выходе — тот же тип
``DimLine``, поэтому сопоставление подписи с отрезком, разбор выносок,
иерархия «звено / обобщённый» и подсчёт сумм переиспользуются из ``dimscan``
без изменений.

Модули:

``render``      Рендер листа и профили деградации: чисто / скан / фото.
``words``       Приведение строки OCR к числу и обратно.
``engines``     Общий интерфейс распознавания: Tesseract, PaddleOCR, EasyOCR.
``arrows``      Наконечники стрелок в растре: контуры, площадь, остриё.
``lines``       Отрезок = пара наконечников, остриё к острию.
``detect_raster`` Склейка ``arrows`` + ``lines`` + ``words`` в ``DimLine[]``.
``roi``         Повторное чтение числа в кропе вокруг отрезка.
``vote``        Согласование прочтений, статус каждого размера.
``evaluate``    Эталон из векторного ``dimscan``, метрики, отчёт.
"""
