"""Приведение строки OCR к числу и обратно.

Распознанная подпись почти никогда не приходит ровно. На изометрии это не
абстрактная проблема, а конкретная: подписи нарисованы узким шрифтом
(``ArialNarrow``, шаг цифры 3.4 pt при капители 5.3 pt), и на скане капитель
падает до 11-15 px. Дальше работает типичный набор подмен, и почти каждая из
них означает конкретную ошибку:

``O`` и ``0``   на узком шрифте это один и тот же овал; по форме не отличить
                в принципе, решает только контекст — «6OOO» в сумме не
                сходится, поэтому в число превращается нуль;
``I``, ``l``, ``1``  вертикальная черта; в чертеже рядом с числом стоят
                диаметры ``DN50`` и координаты, поэтому одиночная ``l``
                почти наверняка единица;
``S`` и ``5``, ``B`` и ``8``, ``Z`` и ``2``, ``G`` и ``6``  пары с одинаковым
                числом штрихов, различаются только скруглением;
``O`` вместо ``0`` в ``DN50``  не чинится: сначала отсекаем не-числа
                целиком, и только потом чистим то, что осталось.

Отдельно осторожно с ``<`` и ``>``: на чертеже они означают «меньше» и
«больше» (``<2>`` — это номер оси, а не число), и в подпись размера попадать
не должны. В ``dimscan`` они снимались регуляркой ещё до сюда, здесь то же
самое, но позже: сначала убрать всё, что не цифра, потом уже чистить цифры.

Порядок именно такой не по вкусу, а по надёжности: сначала отсечь то, что
заведомо не число, иначе подстановка превратит ``DN50`` в ``D50`` и такое
прочтение будет выглядеть правдоподобнее настоящего.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, field

# Подстановки внутри уже числовой строки. Ключ — что распозналось, значение —
# чем заменяем. Порядок словаря сохранять нельзя при обходе посимвольно:
# ``I`` и ``l`` заменяются на ``1`` независимо, ``O`` — на ``0``, и всё.
_CONFUSABLES = {
    "O": "0", "o": "0", "Q": "0", "D": "0",
    "I": "1", "l": "1", "i": "1", "|": "1", "!": "1", "]": "1",
    "S": "5", "s": "5",
    "B": "8",
    "Z": "2", "z": "2",
    "G": "6", "b": "6",
    "T": "7",
    "A": "4",
}

# Полноширинные цифры и прочие юникод-замены: в распознавании встречаются,
# особенно после копирования из сторонних источников.
_UNICODE_DIGITS = {
    "０": "0", "１": "1", "２": "2", "３": "3", "４": "4",
    "５": "5", "６": "6", "７": "7", "８": "8", "９": "9",
}

_NUM_CLEAN_RE = re.compile(r"[^0-9.,]")
_WHOLE_RE = re.compile(r"^\d+(?:[.,]\d+)?$")
_HAS_DIGIT_RE = re.compile(r"\d")

# Знаки, которые на чертеже означают неравенство, а на скане распознаются как
# цифры или как одиночные точки. Их нельзя молча выбрасывать внутри числа:
# «12<8» значит «меньше 128» и превращать его в «128» нельзя, а вот у
# одиночной подписи «<» — обычный мусор. Разбираем по месту.
_RELATION_CHARS = "<>"


@dataclass
class NumberReading:
    """Результат разбора одной прочитанной строки."""

    raw: str
    value: float | None = None
    digits: int = 0
    #: что именно пришлось исправить: ``O→0``, запятая, мусор по краям
    fixes: list[str] = field(default_factory=list)
    reason: str = ""

    @property
    def ok(self) -> bool:
        return self.value is not None

    def as_dict(self) -> dict:
        return {
            "raw": self.raw,
            "value": self.value,
            "digits": self.digits,
            "fixes": self.fixes,
            "reason": self.reason,
        }


def normalize(raw: str) -> str:
    """Грубое приведение к виду, пригодному для проверки регуляркой."""
    text = unicodedata.normalize("NFKC", raw or "")
    for bad, good in _UNICODE_DIGITS.items():
        text = text.replace(bad, good)
    return text.strip()


def is_number(raw: str) -> bool:
    """Похоже ли это на подпись размера — до всякой очистки.

    Строгое условие: только цифры, опционально одна точка или запятая
    внутри. Всё остальное — не число, и разбирать его дальше незачем: так
    отсекаются ``DN50``, ``ШТУРВАЛ``, ``X 48600`` и ``LT 4116``, которые на
    листе стоят рядом с размерами и на расстоянии в несколько пунктов
    выглядят для геометрии одинаково.
    """
    text = normalize(raw)
    if not text:
        return False
    if any(char in _RELATION_CHARS for char in text):
        return False
    if not _WHOLE_RE.match(text):
        return False
    # Одна цифра без разделителя — скорее номер оси или поз. знак, а не
    # размер: на этих листах минимальная подпись размера состоит из двух
    # цифр, а одиночные «5», «7», «9» встречаются только как номера.
    if len(text) == 1:
        return False
    return True


def _resolve_separator(working: str, fixes: list[str]) -> tuple[str, str]:
    """Разобраться с точкой и запятой в подписи размера.

    Настоящая дробная часть на этих листах не встречается: все подписи
    размеров — целые миллиметры. Точка или запятая в распознанной строке
    почти всегда означает не дробь, а мусор: лишний знак, обрывок
    координаты, ошибка детектора. Причём само значение от этого меняется
    радикально — «6,OOO» превращается в 6.0 вместо 6000, и это молчаливое
    искажение хуже явного отказа.

    Поэтому разделитель трактуется как дробь только когда это правдоподобно
    по числу цифр: целая часть не длиннее трёх цифр, дробная — одна или две.
    Во всех остальных случаях разделитель убирается, а подпись читается как
    целое число из всех цифр подряд, и факт замены попадает в отчёт.
    """
    count = working.count(".") + working.count(",")
    if count == 0:
        return working, ""

    if count == 1:
        position = max(working.rfind("."), working.rfind(","))
        whole = re.sub(r"\D", "", working[:position])
        fraction = re.sub(r"\D", "", working[position + 1:])
        if whole and 1 <= len(whole) <= 3 and fraction and len(fraction) <= 2:
            return f"{whole}.{fraction}", "запятая/точка как дробь"

    # Не дробь: убираем разделители и читаем все цифры подряд. Именно так
    # «6,OOO» становится 6000, а не 6.0, и несошедшаяся сумма по листу
    # покажет, что подпись прочитана неверно.
    digits = re.sub(r"\D", "", working)
    if not digits:
        return working, "разделители убраны, цифр нет"
    return digits, "разделитель убран, прочитано целое"


def parse(raw: str, *, allow_single_digit: bool = False) -> NumberReading:
    """Разобрать прочитанную строку в число или объяснить, почему не вышло.

    ``allow_single_digit`` нужен для случаев, где размер в одну цифру
    возможен: на других экспортированных комплектах такой размер
    встречается, и молча выбрасывать его нельзя. На наших листах одиночные
    числа — это номера осей, поэтому по умолчанию они отбрасываются.
    """
    text = normalize(raw)
    if not text:
        return NumberReading(raw=raw, reason="пусто")

    for char in _RELATION_CHARS:
        if char in text:
            return NumberReading(raw=raw, reason="знак неравенства")

    if not allow_single_digit and len(text) == 1 and text.isdigit():
        return NumberReading(raw=raw, reason="одна цифра")

    if not _HAS_DIGIT_RE.search(text):
        return NumberReading(raw=raw, reason="нет цифр")

    working = text
    fixes: list[str] = []

    # Сначала убираем всё, что не может быть частью числа. Отдельно отмечаем
    # подмены «похожих» символов: по ним видно, где именно распознавание
    # было неуверенным, и это попадает в отчёт как подсказка, а не как
    # молчаливое исправление.
    out: list[str] = []
    for char in working:
        if char.isdigit() or char in ".,":
            out.append(char)
            continue
        replacement = _CONFUSABLES.get(char)
        if replacement is not None:
            out.append(replacement)
            fixes.append(f"{char}->{replacement}")
        else:
            fixes.append("мусор убран")
    working = "".join(out)

    if not working:
        return NumberReading(raw=raw, reason="не осталось цифр")

    working, sep_fix = _resolve_separator(working, fixes)
    if sep_fix:
        fixes.append(sep_fix)

    if not _WHOLE_RE.match(working):
        return NumberReading(raw=raw, reason="не число после очистки")

    try:
        value = float(working)
    except ValueError:
        return NumberReading(raw=raw, reason="не разобралось число")

    digits = len(re.sub(r"\D", "", working))
    return NumberReading(raw=raw, value=value, digits=digits, fixes=fixes)


def is_plausible(value: float) -> tuple[bool, str]:
    """Отсечь то, что размером быть не может.

    Не «после распознавания», а до: значение приходит из разбора строки, и
    часть ошибок видна только в самом числе. На изометрии длина участка
    измеряется в миллиметрах и всегда круглая по последним разрядам;
    значение с длинной дробной частью почти наверняка означает, что в
    подпись попал кусок координаты вида ``130650``, разбитый точкой.
    """
    if value <= 0:
        return False, "не положительное"
    if value > 1_000_000:
        return False, "слишком велико для длины в мм"
    fraction = value - int(value)
    if abs(fraction) > 1e-6:
        return False, "дробное: вероятно кусок координаты"
    if abs(value) > 100 and value % 100 == 0 and int(value) % 10 == 0:
        # Типичная подмена «6OOO» → «6000» проходит все проверки, и её
        # ловит только арифметика листа. Помечаем явно, чтобы сумма по
        # листу показала расхождение, а не молча сошлась.
        return True, "круглое до 100"
    return True, ""
